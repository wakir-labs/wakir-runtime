def render_prometheus(
    envelope: Mapping[str, Any], *, scrape_ts_utc: Optional[int] = None
) -> str:
    """Render the envelope as Prometheus exposition text.

    Metric schema (all gauges)::

        persona_engine_backend_decisions_sample_size
        persona_engine_backend_decisions_window_size
        persona_engine_backend_decisions_per_component_backend{component="...",backend="..."}
        persona_engine_backend_decisions_per_component{component="..."}
        persona_engine_backend_decision_latency_us{component="...",quantile="0.5|0.95|0.99"}
        persona_engine_backend_decision_latency_us_avg{component="..."}
        persona_engine_backend_decision_count_per_component{component="..."}
        persona_engine_backend_decision_fallbacks_total{component="..."}
        persona_engine_backend_decision_fallback_rate{component="..."}
        persona_engine_backend_decision_fallback_rate_aggregated
        persona_engine_backend_decisions_scrape_timestamp_seconds
    """
    if scrape_ts_utc is None:
        scrape_ts_utc = int(time.time())
    lines: List[str] = []

    def _emit_help(name: str, help_text: str, mtype: str = "gauge") -> None:
        lines.append(f"# HELP {name} {help_text}\n")
        lines.append(f"# TYPE {name} {mtype}\n")

    _emit_help(
        "persona_engine_backend_decisions_sample_size",
        "Number of backend-decision records aggregated in the current window.",
    )
    lines.append(
        f"persona_engine_backend_decisions_sample_size {envelope['sample_size']}\n"
    )

    _emit_help(
        "persona_engine_backend_decisions_window_size",
        "Configured sliding-window size (WAKIR_BACKEND_DECISION_OBS_WINDOW).",
    )
    lines.append(
        f"persona_engine_backend_decisions_window_size {envelope['window_size']}\n"
    )

    _emit_help(
        "persona_engine_backend_decisions_per_component_backend",
        "Per (component, chosen-backend) count of decisions in the current window.",
    )
    for component in sorted(envelope["count_per_component_backend"].keys()):
        per_backend = envelope["count_per_component_backend"][component]
        for backend in sorted(per_backend.keys()):
            value = per_backend[backend]
            lines.append(
                'persona_engine_backend_decisions_per_component_backend'
                f'{{component="{_escape_label(component)}",'
                f'backend="{_escape_label(backend)}"}} {value}\n'
            )

    _emit_help(
        "persona_engine_backend_decisions_per_component",
        "Per-component total decision count in the current window.",
    )
    for component in sorted(envelope["count_per_component"].keys()):
        value = envelope["count_per_component"][component]
        lines.append(
            'persona_engine_backend_decisions_per_component'
            f'{{component="{_escape_label(component)}"}} {value}\n'
        )

    _emit_help(
        "persona_engine_backend_decision_latency_us",
        "Per-component nearest-rank decision-resolution-latency percentile (microseconds).",
    )
    for component in sorted(envelope["latency_per_component"].keys()):
        bucket = envelope["latency_per_component"][component]
        for q_label, q_key in (
            ("0.5", "p50"),
            ("0.95", "p95"),
            ("0.99", "p99"),
        ):
            lines.append(
                'persona_engine_backend_decision_latency_us'
                f'{{component="{_escape_label(component)}",'
                f'quantile="{q_label}"}} {bucket[q_key]}\n'
            )

    _emit_help(
        "persona_engine_backend_decision_latency_us_avg",
        "Per-component arithmetic-mean decision-resolution-latency (microseconds).",
    )
    for component in sorted(envelope["latency_per_component"].keys()):
        bucket = envelope["latency_per_component"][component]
        lines.append(
            'persona_engine_backend_decision_latency_us_avg'
            f'{{component="{_escape_label(component)}"}}'
            f" {_format_value(bucket['avg'])}\n"
        )

    _emit_help(
        "persona_engine_backend_decision_count_per_component",
        "Per-component sample-count contributing to the latency percentile "
        "(filtered to records with a valid latency).",
    )
    for component in sorted(envelope["latency_per_component"].keys()):
        bucket = envelope["latency_per_component"][component]
        lines.append(
            'persona_engine_backend_decision_count_per_component'
            f'{{component="{_escape_label(component)}"}} {bucket["count"]}\n'
        )

    _emit_help(
        "persona_engine_backend_decision_fallbacks_total",
        "Per-component count of decisions whose fallback_reason is non-null.",
    )
    for component in sorted(envelope["fallback_counts_per_component"].keys()):
        value = envelope["fallback_counts_per_component"][component]
        lines.append(
            'persona_engine_backend_decision_fallbacks_total'
            f'{{component="{_escape_label(component)}"}} {value}\n'
        )

    _emit_help(
        "persona_engine_backend_decision_fallback_rate",
        "Per-component share of decisions that fell back to Python (0..1).",
    )
    for component in sorted(envelope["fallback_rate_per_component"].keys()):
        value = envelope["fallback_rate_per_component"][component]
        lines.append(
            'persona_engine_backend_decision_fallback_rate'
            f'{{component="{_escape_label(component)}"}}'
            f" {_format_value(value)}\n"
        )

    _emit_help(
        "persona_engine_backend_decision_fallback_rate_aggregated",
        "Cross-component aggregated fallback-rate "
        "(total fallbacks / total decisions, 0..1).",
    )
    lines.append(
        "persona_engine_backend_decision_fallback_rate_aggregated "
        f"{_format_value(envelope['aggregated_fallback_rate'])}\n"
    )

    _emit_help(
        "persona_engine_backend_decisions_scrape_timestamp_seconds",
        "POSIX-epoch timestamp at which the backend-decision aggregator "
        "last wrote the textfile.",
    )
    lines.append(
        "persona_engine_backend_decisions_scrape_timestamp_seconds "
        f"{scrape_ts_utc}\n"
    )

    return "".join(lines)


def _escape_label(v: str) -> str:
    """Prometheus label-value escaping: backslash, double-quote, newline."""
    return v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def _format_value(v: float) -> str:
    """Format a float for Prometheus exposition (parity with sibling aggregators)."""
    if isinstance(v, bool):
        v = int(v)
    if isinstance(v, int):
        return str(v)
    if float(v).is_integer():
        return str(int(v))
    return f"{v:.10f}".rstrip("0").rstrip(".")


# ---------------------------------------------------------------------------
# Atomic textfile write (parity with cache-hit-rate-aggregator)
# ---------------------------------------------------------------------------


def atomic_write(target: Path, payload: str) -> None:
    """Write ``payload`` to ``target`` atomically via os.replace."""
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        dir=str(target.parent),
        prefix=target.name + ".",
        suffix=".tmp",
        delete=False,
        encoding="utf-8",
    ) as tmp:
        tmp.write(payload)
        tmp_path = Path(tmp.name)
    os.replace(tmp_path, target)


