class JsonlReadError(RuntimeError):
    """Raised when the backend-decision JSONL is missing or unreadable."""


# ---------------------------------------------------------------------------
# JSONL parsing + sliding-window selection
# ---------------------------------------------------------------------------


def _is_backend_decision_record(obj: Any) -> bool:
    """Return True when ``obj`` is a dict that looks like a backend-decision.

    Acceptance criteria:
      - ``obj`` is a dict.
      - Either no ``msg`` field is present (liberal-reader: direct
        fixture-emit without engine envelope), or the ``msg`` field
        equals :data:`BACKEND_DECISION_MSG`.

    All other dicts (e.g. observability events, error frames in a
    mixed engine log_sink) are filtered out before aggregation.
    """
    if not isinstance(obj, dict):
        return False
    msg = obj.get("msg")
    if msg is None:
        # No msg envelope — accept (test fixtures often emit raw).
        return True
    return msg == BACKEND_DECISION_MSG


def read_decision_records(jsonl_path: Path) -> List[Dict[str, Any]]:
    """Parse the backend-decision JSONL into a list of dicts.

    Tolerates blank lines and malformed JSON (skips both). Returns
    an empty list when the file is empty; raises
    :class:`JsonlReadError` when the file is missing or unreadable.

    Records whose ``msg`` field is present and not equal to
    :data:`BACKEND_DECISION_MSG` are silently skipped — the engine
    log_sink is a shared stream and other event types must not
    contaminate the aggregator.
    """
    if not jsonl_path.is_file():
        raise JsonlReadError(
            f"backend-decision JSONL {jsonl_path} is not a regular file"
        )
    try:
        with jsonl_path.open("rb") as fh:
            data = fh.read()
    except OSError as exc:
        raise JsonlReadError(
            f"cannot read backend-decision JSONL {jsonl_path}: {exc}"
        ) from exc
    records: List[Dict[str, Any]] = []
    for raw in data.decode("utf-8", errors="replace").splitlines():
        raw = raw.strip()
        if not raw:
            continue
        try:
            obj = json.loads(raw)
        except json.JSONDecodeError:
            continue
        if _is_backend_decision_record(obj):
            records.append(obj)
    return records


def select_window(
    records: List[Dict[str, Any]], window_size: int
) -> List[Dict[str, Any]]:
    """Return the trailing ``window_size`` records (or all if shorter).

    A non-positive ``window_size`` is normalised to
    :data:`DEFAULT_WINDOW_SIZE` so a misconfigured env-var cannot
    silently disable windowing.
    """
    if window_size <= 0:
        window_size = DEFAULT_WINDOW_SIZE
    if len(records) <= window_size:
        return list(records)
    return records[-window_size:]


def read_window_size_from_env(env: Mapping[str, str]) -> int:
    """Return the configured window size from the env-map.

    Invalid values (non-int, <= 0) fall back to
    :data:`DEFAULT_WINDOW_SIZE`. The aggregator never raises on a
    bad env-var — operator misconfiguration must not break the
    metrics pipeline.
    """
    raw = env.get(WAKIR_BACKEND_DECISION_OBS_WINDOW_ENV, "").strip()
    if not raw:
        return DEFAULT_WINDOW_SIZE
    try:
        value = int(raw)
    except ValueError:
        return DEFAULT_WINDOW_SIZE
    if value <= 0:
        return DEFAULT_WINDOW_SIZE
    return value


# ---------------------------------------------------------------------------
# Field extraction helpers
# ---------------------------------------------------------------------------


def _safe_component(value: Any) -> str:
    """Coerce ``domain`` field to a known component or the unknown sentinel."""
    if isinstance(value, str) and value in KNOWN_COMPONENTS:
        return value
    return COMPONENT_UNKNOWN_BUCKET


def _safe_backend(value: Any) -> str:
    """Coerce ``chosen_backend`` to a non-empty str or the unknown sentinel."""
    if isinstance(value, str) and value:
        return value
    return BACKEND_UNKNOWN_BUCKET


def _safe_int_latency(value: Any) -> Optional[int]:
    """Return a non-negative int latency or ``None`` on bad input.

    Tolerates int and float (truncates). Rejects negatives, NaN,
    Inf, bool, and non-numeric types. Mirrors the defensive posture
    of ``routing-decision-observability.py``.
    """
    if isinstance(value, bool):
        # bool is an int subclass; we do not want True == 1us.
        return None
    if isinstance(value, int):
        return value if value >= 0 else None
    if isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            return None
        ival = int(value)
        return ival if ival >= 0 else None
    return None


def _is_fallback(value: Any) -> bool:
    """Return True when ``fallback_reason`` indicates a real fallback.

    A non-null non-empty string is a fallback. ``None``, missing,
    or empty string is not. The substrate writes ``null`` (JSON) for
    the no-fallback case; we treat both ``None`` and empty string
    as equivalent for resilience to fixture drift.
    """
    if value is None:
        return False
    if isinstance(value, str) and value:
        return True
    return False


# ---------------------------------------------------------------------------
# Aggregation
# ---------------------------------------------------------------------------


def _nearest_rank_percentile(
    sorted_values: List[int], pct: float
) -> int:
    """Compute a nearest-rank percentile from a sorted ``int`` list.

    Returns 0 for an empty list. Pct is in [0, 100]. Nearest-rank
    (NIST) is preferred over linear interpolation here because the
    dashboard should display a *real measured latency*, not an
    interpolated phantom that no boot actually exhibited.
    """
    n = len(sorted_values)
    if n == 0:
        return 0
    pct = max(0.0, min(100.0, pct))
    rank = max(1, math.ceil((pct / 100.0) * n))
    rank = min(rank, n)
    return sorted_values[rank - 1]


def aggregate_decisions(
    records: Iterable[Mapping[str, Any]], *, window_size: int
) -> Dict[str, Any]:
    """Aggregate a sequence of BackendDecision records into the envelope.

    See module docstring for the envelope schema.
    """
    records_list = list(records)
    sample = select_window(records_list, window_size)

    count_per_component_backend: Dict[str, Dict[str, int]] = {}
    count_per_component: Dict[str, int] = {}
    latency_by_component: Dict[str, List[int]] = {}
    fallback_counts: Dict[str, int] = {}

    for rec in sample:
        component = _safe_component(rec.get("domain"))
        backend = _safe_backend(rec.get("chosen_backend"))

        per_backend = count_per_component_backend.setdefault(component, {})
        per_backend[backend] = per_backend.get(backend, 0) + 1
        count_per_component[component] = (
            count_per_component.get(component, 0) + 1
        )

        latency = _safe_int_latency(rec.get("resolution_latency_us"))
        if latency is not None:
            latency_by_component.setdefault(component, []).append(latency)

        if _is_fallback(rec.get("fallback_reason")):
            fallback_counts[component] = fallback_counts.get(component, 0) + 1

    latency_per_component: Dict[str, Dict[str, Any]] = {}
    for component, vals in latency_by_component.items():
        vals_sorted = sorted(vals)
        n = len(vals_sorted)
        avg = sum(vals_sorted) / n if n > 0 else 0.0
        latency_per_component[component] = {
            "avg": avg,
            "p50": _nearest_rank_percentile(vals_sorted, 50.0),
            "p95": _nearest_rank_percentile(vals_sorted, 95.0),
            "p99": _nearest_rank_percentile(vals_sorted, 99.0),
            "count": n,
        }

    # Fallback-rate per component. Components with zero observations
    # do not appear in count_per_component, hence the rate dict is
    # keyed by the same set. We intentionally do not pre-seed all
    # KNOWN_COMPONENTS with 0.0: the absence of a component-key in
    # the rate dict means "no observations", which the dashboard
    # renders distinctly from "0% fallback".
    fallback_rate_per_component: Dict[str, float] = {}
    for component, total in count_per_component.items():
        fallbacks = fallback_counts.get(component, 0)
        if total > 0:
            fallback_rate_per_component[component] = fallbacks / total
        else:
            fallback_rate_per_component[component] = 0.0

    total_decisions = sum(count_per_component.values())
    total_fallbacks = sum(fallback_counts.values())
    if total_decisions > 0:
        aggregated_fallback_rate = total_fallbacks / total_decisions
    else:
        aggregated_fallback_rate = 0.0

    return {
        "sample_size": len(sample),
        "window_size": window_size,
        "count_per_component_backend": count_per_component_backend,
        "count_per_component": count_per_component,
        "latency_per_component": latency_per_component,
        "fallback_counts_per_component": fallback_counts,
        "fallback_rate_per_component": fallback_rate_per_component,
        "aggregated_fallback_rate": aggregated_fallback_rate,
    }


