#: Env-var the persona-engine writes its log_sink to. The
#: BackendDecision records flow through that sink alongside other
#: structured events. The aggregator filters by ``msg`` field, so
#: pointing this at the engine's main log_sink path is correct.
#: When the deployment splits BackendDecision into a dedicated
#: sink (future hardening), the same env-var continues to work.
WAKIR_BACKEND_DECISION_JSONL_ENV = "WAKIR_BACKEND_DECISION_JSONL"

#: Env-var the aggregator reads to size the sliding window.
WAKIR_BACKEND_DECISION_OBS_WINDOW_ENV = "WAKIR_BACKEND_DECISION_OBS_WINDOW"

#: Default sliding-window size when the env-var is unset or
#: non-positive. Half the routing-decisions default (1000) since
#: BackendDecisions are emitted at boot-cadence, not per-request.
DEFAULT_WINDOW_SIZE = 500

#: Default textfile-collector output path (parity with sibling
#: aggregators).
DEFAULT_TEXTFILE_OUTPUT = (
    "/var/lib/node_exporter/textfile_collector/backend_decisions.prom"
)

#: Components per ADR-0061 et seq (Phase-3b switches). Mirrors the
#: ``domain=...`` values emitted by
#: :mod:`wirelang.persona_engine.rust_backend_switch`. Kept locally
#: so the aggregator stays stdlib-only.
COMPONENT_RECOVERY = "recovery"
COMPONENT_STATE_BACKING = "state_backing"
COMPONENT_FSM = "fsm"
COMPONENT_V907_VERIFY = "v907_verify"
COMPONENT_BRIDGE_DIFF = "bridge_diff"

KNOWN_COMPONENTS = (
    COMPONENT_RECOVERY,
    COMPONENT_STATE_BACKING,
    COMPONENT_FSM,
    COMPONENT_V907_VERIFY,
    COMPONENT_BRIDGE_DIFF,
)

#: Bucket key for records whose ``domain`` field is missing or not
#: in :data:`KNOWN_COMPONENTS`. Drift surfaces in the unknown gauge.
COMPONENT_UNKNOWN_BUCKET = "component_unknown"

#: Bucket key for records whose ``chosen_backend`` field is null /
#: missing. We do not silently drop these.
BACKEND_UNKNOWN_BUCKET = "backend_unknown"

#: Wire-string the engine emits to identify a BackendDecision record
#: in a mixed log_sink stream. Anything else is skipped during
#: aggregation; records without a ``msg`` field are accepted (liberal
#: reader for direct-fixture-emit test inputs).
BACKEND_DECISION_MSG = "backend-decision"


