"""backend-decision-observability — Tag-22 Backend-Decision-Aggregator (SRE).

Background
----------

Phase-3b production-default switches (Tag-17 through Tag-21) wire five
``BackendDecision`` emit points in
:mod:`wirelang.persona_engine.rust_backend_switch`, one per
component:

  * ``recovery``      — Tag-17 (PR #168)
  * ``state_backing`` — Tag-17 (PR #168, twin emit-point)
  * ``fsm``           — Tag-18 (PR #169)
  * ``v907_verify``   — Tag-19 (PR #171)
  * ``bridge_diff``   — Tag-20 (PR #175)

Each engine boot emits one ``BackendDecision`` record per component
through :func:`log_backend_decision` into the engine's log_sink. The
on-disk schema (see ``log_backend_decision`` in
``wirelang/persona_engine/rust_backend_switch.py``) is::

    {
        "level": "INFO",
        "msg": "backend-decision",
        "domain": "recovery|state_backing|fsm|v907_verify|bridge_diff",
        "requested_backend": "<env-normalised>",
        "chosen_backend": "rust|python|rust_inmemory|rust_natskv|...",
        "resolution_latency_us": <int>,
        "fallback_reason": "binary_missing|binary_not_executable|explicit_python|null",
        "bin_path": "<path>|null"
    }

Until this Tag-22 aggregator lands, there is no centralized
observability over these records: an operator who wants to know
"what share of Phase-3b boots are still falling back to Python on
the v907_verify component" has to grep the JSONL by hand. This
aggregator is the SRE-side substrate that turns the per-boot
records into a five-component dashboard.

It is the **per-component-backend parallel** to the existing
per-routing-mode aggregator (Noa Tag-16, PR #161) and per-model
cost aggregator (Noa PR #110). Together those three views answer
"which model did the router pick" (Tag-16), "what did each model
cost" (PR #110), and now "which language backend did each engine
component boot under" (Tag-22).

The companion Grafana dashboard is
``dashboards/persona-engine-backend-decisions.json``.

Schema alignment
----------------

The emit-point uses the field name ``domain`` for historical reasons
(it predates the formal Phase-3b naming). The aggregator and
dashboard surface this as ``component`` — operator-facing copy uses
"component" consistently with the Phase-3b ADRs (ADR-0061 et seq).
The JSONL field name itself is **not** renamed: every consumer of
this aggregator reads the JSONL through this module, and the
emit-point's existing audit-trail must remain byte-stable for
verifier replay. The mapping is purely a metric-label rename.

The aggregator also tolerates engine log_sink streams that
interleave ``backend-decision`` records with other structured
``msg``-tagged records (e.g. observability events, error frames).
Only records whose ``msg`` field equals ``"backend-decision"`` are
aggregated. Records without a ``msg`` field are accepted under the
liberal-reader principle — fixtures generated by tests that emit
the record directly (without an engine wrapper) lack the ``msg``
envelope but still carry the substantive fields.

Sliding-window semantics
------------------------

BackendDecision JSONL grows one record per component per engine
boot. At Wakir-internal boot cadence (≤ a few dozen boots per
hour) the file remains modest, but the aggregator still applies a
trailing-window discipline (parity with
``routing-decision-observability.py``) so the gauges reflect the
recent operational reality rather than the historical long-tail.

Window size is operator-tunable via ``WAKIR_BACKEND_DECISION_OBS_WINDOW``
(default 500 — half the routing-decisions default since
per-boot-cardinality is one record-per-component vs.
per-decision-cardinality of one-per-request).

Aggregations
------------

The aggregator returns a single envelope dict with these top-level
keys:

  - ``sample_size``: number of decisions aggregated (0..N).
  - ``window_size``: configured N.
  - ``count_per_component_backend``: dict
    ``{component -> {backend -> int}}`` giving the python-vs-rust
    split per component. ``backend`` is the JSONL ``chosen_backend``
    value, lower-cased; null/missing maps to the sentinel
    ``backend_unknown``. Unknown components map to
    ``component_unknown``.
  - ``count_per_component``: dict ``{component -> int}`` total
    decisions per component (sum of the inner dict). Useful for
    quick parity-check "did all 5 components emit this boot".
  - ``latency_per_component``: dict
    ``{component -> {avg, p50, p95, p99, count}}`` with
    **nearest-rank** percentile semantics over
    ``resolution_latency_us`` (microseconds). ``avg`` is float; the
    quantile keys are integers; ``count`` is the per-component
    sample size after dropping records with malformed/missing
    latency.
  - ``fallback_counts_per_component``: dict ``{component -> int}``
    of decisions whose ``fallback_reason`` is a non-null string.
    A fallback signals the operator-requested backend was not
    available and the switch coerced down to Python.
  - ``fallback_rate_per_component``: dict ``{component -> float}``
    of ``fallbacks / decisions`` in [0, 1]; 0.0 when the
    component has zero observations (an explicit zero-traffic
    rule, not silent-1.0).
  - ``aggregated_fallback_rate``: float of total-fallbacks /
    total-decisions across all components; 0.0 when sample is
    empty.

Outputs
-------

Two output formats:

  - ``--format=json``: the envelope above as a single JSON object.
    Operator-facing; default.
  - ``--format=prometheus``: Prometheus exposition format for the
    node-exporter textfile collector.

The two formats expose the same numbers. The Grafana dashboard
``dashboards/persona-engine-backend-decisions.json`` consumes the
Prometheus gauges.

Run mode
--------

Stdlib-only. Driven by a 5-minute systemd-user-timer cadence
inside the ``claude-dev`` toolbox container — the same substrate
Kai already runs for the cost, cache, and routing aggregators.

Exit codes
----------

* ``0`` — aggregator ran cleanly.
* ``1`` — JSONL path missing or unreadable.
* ``2`` — textfile output directory not writable (Prometheus mode).

License: Apache-2.0 (parity with sibling aggregators).
"""

