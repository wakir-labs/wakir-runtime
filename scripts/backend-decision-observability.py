def build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="backend-decision-observability",
        description=(
            "Aggregator for per-boot BackendDecision telemetry emitted by "
            "the Phase-3b production-default switches in "
            "wirelang.persona_engine.rust_backend_switch. Outputs JSON "
            "for operators or Prometheus exposition for the "
            "node-exporter textfile collector. Tag-22 SRE artefact."
        ),
    )
    p.add_argument(
        "--jsonl-path",
        type=Path,
        default=None,
        help=(
            "Path to the backend-decision JSONL (engine log_sink). "
            f"Falls back to ${WAKIR_BACKEND_DECISION_JSONL_ENV}."
        ),
    )
    p.add_argument(
        "--window-size",
        type=int,
        default=None,
        help=(
            "Sliding-window size (most recent N decisions). Falls back "
            f"to ${WAKIR_BACKEND_DECISION_OBS_WINDOW_ENV} then "
            f"{DEFAULT_WINDOW_SIZE}."
        ),
    )
    p.add_argument(
        "--format",
        choices=("json", "prometheus"),
        default="json",
        help="Output format: json (default, operator-facing) or prometheus.",
    )
    p.add_argument(
        "--textfile-output",
        type=Path,
        default=Path(DEFAULT_TEXTFILE_OUTPUT),
        help=(
            "Prometheus textfile-collector output path (only used when "
            f"--format=prometheus). Default: {DEFAULT_TEXTFILE_OUTPUT}"
        ),
    )
    p.add_argument(
        "--now",
        type=int,
        default=None,
        help=(
            "Override the 'now' POSIX-epoch timestamp for hermetic tests. "
            "Production runs leave this unset and use time.time()."
        ),
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help=(
            "In --format=prometheus mode: render to stdout instead of "
            "writing the textfile. In --format=json mode: no-op."
        ),
    )
    return p


def resolve_jsonl_path(
    cli_value: Optional[Path], env: Mapping[str, str]
) -> Optional[Path]:
    if cli_value is not None:
        return cli_value
    env_value = env.get(WAKIR_BACKEND_DECISION_JSONL_ENV, "").strip()
    if env_value:
        return Path(env_value)
    return None


def resolve_window_size(
    cli_value: Optional[int], env: Mapping[str, str]
) -> int:
    if cli_value is not None:
        if cli_value <= 0:
            return DEFAULT_WINDOW_SIZE
        return cli_value
    return read_window_size_from_env(env)


def main(
    argv: Optional[List[str]] = None,
    *,
    env: Optional[Mapping[str, str]] = None,
) -> int:
    args = build_argparser().parse_args(argv)
    env_map: Mapping[str, str] = env if env is not None else os.environ

    jsonl_path = resolve_jsonl_path(args.jsonl_path, env_map)
    if jsonl_path is None:
        sys.stderr.write(
            "backend-decision-observability: no JSONL path configured "
            f"(set --jsonl-path or ${WAKIR_BACKEND_DECISION_JSONL_ENV}).\n"
        )
        return 1

    try:
        records = read_decision_records(jsonl_path)
    except JsonlReadError as exc:
        sys.stderr.write(f"backend-decision-observability: {exc}\n")
        return 1

    window_size = resolve_window_size(args.window_size, env_map)
    envelope = aggregate_decisions(records, window_size=window_size)

    if args.format == "json":
        sys.stdout.write(json.dumps(envelope, sort_keys=True, indent=2))
        sys.stdout.write("\n")
        return 0

    # Prometheus path.
    now = args.now if args.now is not None else int(time.time())
    payload = render_prometheus(envelope, scrape_ts_utc=now)
    if args.dry_run:
        sys.stdout.write(payload)
        return 0
    try:
        atomic_write(args.textfile_output, payload)
    except OSError as exc:
        sys.stderr.write(
            f"backend-decision-observability: cannot write textfile output: {exc}\n"
        )
        return 2
    return 0


